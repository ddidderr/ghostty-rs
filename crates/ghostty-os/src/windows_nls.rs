/// Cross-platform implementation of `ntdll.RtlUpcaseUnicodeChar`.
/// Transforms the UTF-16 code unit in `c` to its uppercased version if there
/// is one. Otherwise, returns `c` unmodified.
#[must_use]
pub fn upcase_w(c: u16) -> u16 {
    if c < u16::from(b'a') {
        return c;
    }
    if c <= u16::from(b'z') {
        return c - (u16::from(b'a') - u16::from(b'A'));
    }
    if c >= 0xC0 {
        let mut offset: u16 = 0;

        offset = offset.wrapping_add(u16::from((c >> 8) as u8));
        offset = UPPERCASE_TABLE[usize::from(offset)];
        offset = offset.wrapping_add((c >> 4) & 0xF);
        offset = UPPERCASE_TABLE[usize::from(offset)];
        offset = offset.wrapping_add(c & 0xF);
        offset = UPPERCASE_TABLE[usize::from(offset)];

        return c.wrapping_add(offset);
    }
    c
}

#[cfg(test)]
mod tests {
    use super::upcase_w;

    #[test]
    fn ascii_and_latin() {
        assert_eq!(upcase_w(u16::from(b'a')), u16::from(b'A'));
        assert_eq!(upcase_w(u16::from(b'Z')), u16::from(b'Z'));
        assert_eq!(upcase_w(u16::from(b'_')), u16::from(b'_'));
        assert_eq!(upcase_w(0xE9), 0xC9); // e acute
        assert_eq!(upcase_w(0xFF), 0x178); // y diaeresis
        assert_eq!(upcase_w(0xDF), 0xDF); // sharp s has no simple uppercase
    }

    #[test]
    fn matches_the_windows_table_not_modern_unicode() {
        // Windows folds the Greek prosgegrammeni forms U+1F80 -> U+1F88.
        assert_eq!(upcase_w(0x1F88), 0x1F88);
        assert_eq!(upcase_w(0x1F80), 0x1F88);
        // U+1E9E (capital sharp s) and U+A64A-era additions are unchanged.
        assert_eq!(upcase_w(0x1E9E), 0x1E9E);
        // Georgian Mtavruli (U+1C90) is newer than the table: its lowercase
        // U+10D0 maps to nothing under Windows but to U+1C90 in Unicode.
        assert_eq!(upcase_w(0x10D0), 0x10D0);
        // Surrogate halves are untouched.
        assert_eq!(upcase_w(0xD800), 0xD800);
        assert_eq!(upcase_w(0xDFFF), 0xDFFF);
    }
}
